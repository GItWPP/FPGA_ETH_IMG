"""Train/export the FPGA integer-HOG pedestrian model; no training dependency in EXE."""
from pathlib import Path
import hashlib
import json
import re
import struct
import zlib
import numpy as np
from PIL import Image
from sklearn.svm import LinearSVC
from sklearn.metrics import confusion_matrix
from hog_reference import extract_window
from generate_algorithm_modules import write, ROOT, RTL

DATA = ROOT / 'tools/datasets/inria_hog'
SEED = 20261021


def features(gray, x, y):
    """Vectorized implementation checked against the independent scalar reference."""
    a = np.asarray(gray, dtype=np.int16)
    a = np.pad(a, 1, mode='edge')
    gx = a[y+1:y+129, x+2:x+66] - a[y+1:y+129, x:x+64]
    gy = a[y+2:y+130, x+1:x+65] - a[y:y+128, x+1:x+65]
    ax, ay = np.abs(gx).astype(np.int32), np.abs(gy).astype(np.int32)
    q = ay * 256
    bins = np.select([q < ax*93, q < ax*215, q < ax*443, q < ax*1452], [0,1,2,3], 4)
    bins = np.where((gx < 0) != (gy < 0), 8-bins, bins)
    bins = np.where(ay == 0, 0, bins)
    yy, xx = np.indices((128,64))
    index = ((yy//8)*8 + xx//8)*9 + bins
    hist = np.bincount(index.ravel(), weights=(ax+ay).ravel(), minlength=16*8*9).astype(np.int32).reshape(16,8,9)
    blocks = np.concatenate([hist[:-1,:-1],hist[:-1,1:],hist[1:,:-1],hist[1:,1:]],axis=2)
    return (blocks*1024//(blocks.sum(axis=2,keepdims=True)+1)).astype(np.uint16).ravel()


def main():
    rng = np.random.default_rng(SEED)
    source = json.loads((DATA/'source.json').read_text())
    grouped = {}
    for item in source['files']:
        path = Path(item['path'])
        key = item['category'] + '/' + re.sub('[a-z]+$', '', path.stem)
        grouped.setdefault(key, []).append(item)
    train, valid = [], []
    for category in ('pedestrians','no_pedestrians'):
        keys = sorted(k for k in grouped if k.startswith(category+'/'))
        rng.shuffle(keys)
        nvalid = max(1, len(keys)//5)
        for i,key in enumerate(keys):
            (valid if i < nvalid else train).extend(grouped[key])
    datasets = []
    for split, files in [('train',train),('validation',valid)]:
        vectors, labels, origins = [], [], []
        for i,item in enumerate(files):
            image = Image.open(DATA/item['path']).convert('L')
            gray = np.asarray(image)
            positive = item['category']=='pedestrians'
            if positive:
                # INRIA normalized positive crops include 16-pixel context on every side.
                positions = [((image.width-64)//2, (image.height-128)//2)]
            else:
                positions = [(int(rng.integers(0,(image.width-64)//8+1))*8,
                              int(rng.integers(0,(image.height-128)//8+1))*8) for _ in range(12)]
            for x,y in positions:
                vector = features(gray,x,y)
                if len(vectors)<3:
                    assert vector.tolist()==extract_window(image.tobytes(),image.width,image.height,x,y)
                vectors.append(vector)
                labels.append(int(positive))
                origins.append([item['path'],x,y])
        datasets.append((np.array(vectors),np.array(labels),origins))
        print(split, len(vectors), 'positive',sum(labels),flush=True)
    x,y,_ = datasets[0]
    vx,vy,_ = datasets[1]
    best = None
    trials = []
    for c in (0.01,0.1,1.0):
        model=LinearSVC(C=c,class_weight='balanced',dual='auto',max_iter=20000,random_state=SEED)
        model.fit(x.astype(np.float32)/1024,y)
        scores=model.decision_function(vx.astype(np.float32)/1024)
        cm=confusion_matrix(vy,scores>0).tolist()
        tn,fp,fn,tp=np.asarray(cm).ravel()
        quality=tp/(tp+fn)-2*fp/(fp+tn)
        trials.append({'C':c,'confusion_matrix':cm})
        if best is None or quality>best[0]: best=(quality,model)
    model=best[1]
    weights=np.rint(model.coef_.ravel()*4096).astype(np.int64)
    bias=int(round(model.intercept_[0]*(1<<22)))
    assert np.max(np.abs(weights))<32768 and -(1<<31)<=bias<(1<<31)
    raw=vx.astype(np.int64)@weights+bias
    cm=confusion_matrix(vy,raw>0).tolist()
    float_scores=model.decision_function(vx.astype(np.float32)/1024)
    packed=struct.pack('<i',bias)+struct.pack('<3780h',*weights)
    model_id=zlib.crc32(packed)
    threshold=0
    model_text=('"""Generated by train_hog_model.py; integer-HOG v1, not OpenCV HOG weights."""\n'
                f'MODEL_ID = 0x{model_id:08X}\nBIAS = {bias}\nSCORE_SHIFT = 22\nTHRESHOLD = {threshold}\nWEIGHTS = (\n')
    model_text+=''.join('    '+', '.join(str(int(v)) for v in weights[i:i+18])+',\n' for i in range(0,len(weights),18))+')\n'
    (ROOT/'tools/hog_model.py').write_text(model_text,encoding='utf-8')
    (RTL/'hog_svm_weights.mem').write_text(''.join(f'{int(w)&65535:04x}\n' for w in weights),encoding='ascii')
    write('hog_svm_model','整数HOG专用已训练线性SVM权重ROM与模型标识', '''    input   wire            sys_clk,
    input   wire    [11:0]  weight_rd_addr,
    output  reg signed [15:0] weight_rd_data,
    output  wire signed [31:0] bias,
    output  wire    [31:0]  model_id''', '''//reg   define
(* rom_style = "block" *) reg signed [15:0] weights [0:3779];''',f'''assign bias = 32'h{bias&0xffffffff:08x};
assign model_id = 32'h{model_id:08x};

//训练工具导出，与软件参考使用同一模型；文件纳入Vivado工程
initial
    $readmemh("hog_svm_weights.mem", weights);

always@(posedge sys_clk)
    weight_rd_data <= weights[weight_rd_addr];''')
    manifest={'model_id':f'{model_id:08X}','seed':SEED,'source':source['source'],'revision':source['revision'],
              'descriptor':'hard 9-bin unsigned gradient / 8x8 cells / L1 Q10 2x2 blocks',
              'window':[64,128],'weight_fraction_bits':12,'score_fraction_bits':22,'threshold':threshold,
              'weights_sha256':hashlib.sha256(packed).hexdigest(),
              'split_rule':'80/20 by full image stem without final mirror/crop suffix; random subset, not official benchmark split',
              'train_images':[i['path'] for i in train],'validation_images':[i['path'] for i in valid],
              'train_windows':len(x),'validation_windows':len(vx),'trials':trials,'selected_C':model.C,
              'quantized_confusion_matrix_rows_true_0_1_cols_pred_0_1':cm,
              'quantized_disagreements':int(np.count_nonzero((raw>0)!=(float_scores>0))),
              'limitation':'Window classification validation only; no claim of scene-level AP or production readiness.'}
    (ROOT/'doc/hog_model_manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
    # Independent validation artifacts use held-out positive and held-out background.
    pos=next(i for i in valid if i['category']=='pedestrians')
    neg=next(i for i in valid if i['category']=='no_pedestrians')
    scene=Image.open(DATA/neg['path']).convert('L').resize((320,240))
    crop=Image.open(DATA/pos['path']).convert('L')
    scene.paste(crop,(112,40))
    scene.save(ROOT/'sim/hog_validation_scene.png')
    (ROOT/'sim/hog_frame.mem').write_text(''.join(f'{b:02x}\n' for b in scene.tobytes()),encoding='ascii')
    print(json.dumps({'model_id':manifest['model_id'],'validation_confusion':cm,'quantized_disagreements':manifest['quantized_disagreements']}),flush=True)


if __name__=='__main__': main()
