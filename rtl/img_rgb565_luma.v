//--------------------------------------------------------------------------------------------------------
// 模块： img_rgb565_luma
// Type    : synthesizable
// Standard: Verilog 2001 (IEEE1364-2001)
// 功能： RGB565位复制扩展后计算整数加权8位亮度
// 作者： WANG
// 时间： 26.10.21
//--------------------------------------------------------------------------------------------------------
`timescale  1ns/1ns

module  img_rgb565_luma
(
    input   wire           [15:0]  in_data                ,
    output  wire           [7:0]   gray
);

//********************************************************************//
//****************** Parameter and Internal Signal *******************//
//********************************************************************//
//wire  define
wire           [7:0]   red;
wire           [7:0]   green;
wire           [7:0]   blue;
wire           [15:0]  weighted;

//********************************************************************//
//***************************** Main Code ****************************//
//********************************************************************//
assign red = {in_data[15:11], in_data[15:13]};
assign green = {in_data[10:5], in_data[10:9]};
assign blue = {in_data[4:0], in_data[4:2]};
assign weighted = red * 16'd77 + green * 16'd150 + blue * 16'd29;
assign gray = weighted[15:8];

endmodule
